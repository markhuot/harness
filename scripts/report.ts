// The migration report: every old test and every sim-check / Mac-check check, with where it went.
//
//   bun scripts/report.ts            rewrite next/REPORT.md
//   bun scripts/report.ts --check    exit 1 when the committed file is stale (scripts/report.test.ts does this)
//
// Rows come from static extractors (scripts/report-extract.ts), so this needs no simulator or build.
// Dispositions live in scripts/report-dispositions.ts. The file is the work list and the progress meter:
// an old area may be deleted only when none of its rows is `open`.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { DROPPED, PORTED, type Disposition, dispositionOf, label } from "./report-dispositions";
import { type Row, extractAppChecks, extractBunTests, extractSimChecks, extractSnapshotTests, extractSwiftTests } from "./report-extract";

const root = join(import.meta.dir, "..");
export const REPORT_PATH = "next/REPORT.md";

/** Tracked and untracked-but-not-ignored files, so a test you just wrote is already a row. */
export function listFiles(): string[] {
  const out = Bun.spawnSync(["git", "ls-files", "-co", "--exclude-standard"], { cwd: root }).stdout.toString();
  return out.split("\n").filter(Boolean).sort();
}

/** Every row for one file, by where it lives. The new suite (next/) isn't an old test. */
export function rowsForFile(file: string, src: string): Row[] {
  if (file.startsWith("next/")) return [];
  if (/\.test\.tsx?$/.test(file)) return extractBunTests(file, src);
  if (file.startsWith("ios/HarnessKit/Tests/") && file.endsWith(".swift")) return extractSwiftTests(file, src);
  if (file.startsWith("ios/HarnessSnapshotTests/") && file.endsWith(".swift")) return extractSnapshotTests(file, src);
  if (file === "ios/Tools/sim-check.ts") return extractSimChecks(file, src);
  const macScript = /^app\/scripts\/[^/]+\.ts$/.test(file) || /^app\/scripts\/lib\/[^/]+-check\.ts$/.test(file);
  if (macScript) {
    const rows = extractAppChecks(file, src);
    const topLevel = /^app\/scripts\/[^/]+\.ts$/.test(file);
    if (rows.length === 0 && topLevel) {
      return [{ kind: "app-check", file, group: "", name: "(no checks; a script that drives the app and takes screenshots)" }];
    }
    return rows;
  }
  return [];
}

export function collectRows(files = listFiles(), read = (f: string) => readFileSync(join(root, f), "utf8")): Row[] {
  const rows: Row[] = [];
  for (const f of files) {
    if (!existsSync(join(root, f))) continue;
    rows.push(...rowsForFile(f, read(f)));
  }
  // Tests that moved: the old file is gone; its rows come from where they live now.
  for (const p of PORTED) {
    if (!existsSync(join(root, p.now))) continue;
    for (const r of extractBunTests(p.old, read(p.now))) rows.push({ ...r, ref: p.now });
  }
  for (const d of DROPPED) rows.push({ kind: "bun", file: d.file, group: d.group, name: d.name, lossReason: d.reason });
  return rows;
}

const KIND_AREA: Partial<Record<Row["kind"], string>> = {
  "sim-check": "ios sim-check",
  "app-check": "app checks",
  snapshot: "ios snapshot tests",
  swift: "ios/HarnessKit (swift)",
};

export function areaOf(row: Row): string {
  const fixed = KIND_AREA[row.kind];
  if (fixed) return fixed;
  const dirs = row.file.split("/").slice(0, -1);
  return dirs.length === 0 ? "(repo root)" : dirs.slice(0, 3).join("/");
}

const esc = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");

type Tally = Record<Disposition["status"], number>;
const emptyTally = (): Tally => ({ open: 0, new: 0, walkthrough: 0, harnesskit: 0, loss: 0, kept: 0 });

export function buildReport(rows: Row[]): string {
  const withD = rows.map((row) => ({ row, d: dispositionOf(row), area: areaOf(row) }));
  const areas = [...new Set(withD.map((r) => r.area))].sort();
  const total = emptyTally();
  const byArea = new Map<string, Tally>();
  for (const a of areas) byArea.set(a, emptyTally());
  for (const r of withD) {
    total[r.d.status]++;
    byArea.get(r.area)![r.d.status]++;
  }

  const out: string[] = [];
  out.push("# Test migration report", "");
  out.push(
    "Generated by `bun scripts/report.ts`; do not edit by hand. `scripts/report.test.ts` fails when this file is stale: run the script and commit the result.",
    "",
    "Every old test and every sim-check and Mac-check check is a row, with where it went. Dispositions are set in `scripts/report-dispositions.ts`:",
    "",
    "- **new**: covered by a test in the new suite (`next/`); the old one is deleted only after a spot mutation check shows the new one can fail.",
    "- **walkthrough**: covered by a screen of the iPhone or Mac walkthrough.",
    "- **harnesskit**: covered by a HarnessKit swift test, which needs no simulator; the row names the tests.",
    "- **loss**: accepted loss. The human has signed off on the reason; the row stays listed so it can be revisited at the end.",
    "- **kept**: not part of the retired suite; it stays as it is.",
    "- **open**: no decision yet. An area is deleted only when it has no open rows.",
    "",
    "Names generated at runtime (loops, helpers, `test.each`) appear as their template. Counts are static, so they differ slightly from a run's totals.",
    "",
  );

  out.push("## Progress", "");
  out.push(`${rows.length} rows: ${total.open} open, ${total.new} new, ${total.walkthrough} walkthrough, ${total.harnesskit} HarnessKit, ${total.loss} accepted loss, ${total.kept} kept.`, "");
  out.push("| Area | Rows | Open | New | Walkthrough | HarnessKit | Loss | Kept | Deletable |", "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | :---: |");
  for (const a of areas) {
    const t = byArea.get(a)!;
    const n = t.open + t.new + t.walkthrough + t.harnesskit + t.loss + t.kept;
    out.push(`| ${esc(a)} | ${n} | ${t.open} | ${t.new} | ${t.walkthrough} | ${t.harnesskit} | ${t.loss} | ${t.kept} | ${t.open === 0 ? "yes" : ""} |`);
  }
  out.push("");

  // Accepted losses, grouped by reason. They stay listed after sign-off: the human may bring some back at the end.
  const losses = withD.filter((r) => r.d.status === "loss");
  out.push("## Accepted losses", "", "Signed off by the human. They stay listed here so each can be brought back at the end if it turns out to be missed.", "");
  if (losses.length === 0) out.push("None.", "");
  const reasons = [...new Set(losses.map((r) => (r.d as { reason: string }).reason))];
  for (const reason of reasons) {
    const group = losses.filter((r) => (r.d as { reason: string }).reason === reason);
    out.push(`### ${reason}`, "", `${group.length} rows:`, "");
    for (const r of group) out.push(`- ${esc(r.row.group ? `${r.row.group} › ${r.row.name}` : r.row.name)} (${r.row.file})`);
    out.push("");
  }

  out.push("## Rows", "");
  for (const a of areas) {
    out.push(`### ${esc(a)}`, "");
    const inArea = withD.filter((r) => r.area === a);
    const files = [...new Set(inArea.map((r) => r.row.file))];
    for (const file of files) {
      const rs = inArea.filter((r) => r.row.file === file);
      const labels = rs.map((r) => label(r.d));
      const counts = new Map<string, number>();
      for (const l of labels) counts.set(l, (counts.get(l) ?? 0) + 1);
      const common = [...counts.entries()].sort((x, y) => y[1] - x[1] || x[0].localeCompare(y[0]))[0]![0];
      out.push(`#### ${file}: ${rs.length} ${rs.length === 1 ? "row" : "rows"}, mostly ${common}`, "");
      for (const r of rs) {
        const l = label(r.d);
        const name = r.row.group ? `${r.row.group} › ${r.row.name}` : r.row.name;
        out.push(`- ${esc(name)}${l === common ? "" : ` (${l})`}`);
      }
      out.push("");
    }
  }
  return out.join("\n");
}

if (import.meta.main) {
  const text = buildReport(collectRows());
  const path = join(root, REPORT_PATH);
  if (process.argv.includes("--check")) {
    const current = existsSync(path) ? readFileSync(path, "utf8") : "";
    if (current !== text) {
      console.error(`${REPORT_PATH} is stale: run \`bun scripts/report.ts\` and commit the result.`);
      process.exit(1);
    }
  } else {
    writeFileSync(path, text);
    console.log(`wrote ${REPORT_PATH}`);
  }
}
